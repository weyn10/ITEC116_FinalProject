CREATE DATABASE IF NOT EXISTS `03_hrgms_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `03_hrgms_db`;

CREATE TABLE IF NOT EXISTS `users` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  Email VARCHAR(160) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  Role VARCHAR(30) NOT NULL DEFAULT 'user',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `guests` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `FullName` VARCHAR(255) NOT NULL,
  `Email` VARCHAR(160) NOT NULL,
  `Phone` VARCHAR(255) NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `rooms` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `RoomNumber` VARCHAR(255) NOT NULL,
  `RoomType` VARCHAR(255) NOT NULL,
  `Rate` DECIMAL(12,2) NOT NULL,
  `Status` VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `reservations` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `CheckInDate` DATE NOT NULL,
  `CheckOutDate` DATE NOT NULL,
  `Status` VARCHAR(255) NOT NULL,
  `GuestID` INT NOT NULL,
  `RoomID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_reservations_guestid` FOREIGN KEY (`GuestID`) REFERENCES `guests` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_reservations_roomid` FOREIGN KEY (`RoomID`) REFERENCES `rooms` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `invoices` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `InvoiceNumber` VARCHAR(255) NOT NULL,
  `TotalAmount` DECIMAL(12,2) NOT NULL,
  `PaymentStatus` VARCHAR(255) NOT NULL,
  `ReservationID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_invoices_reservationid` FOREIGN KEY (`ReservationID`) REFERENCES `reservations` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
